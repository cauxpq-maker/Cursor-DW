WRAP = Alignment(wrap_text=True, vertical="center")


def style_header(ws, ncols):
    for col in range(1, ncols + 1):
        cell = ws.cell(2, col)
        cell.font = HEADER_FONT
        cell.fill = FILL_H
        cell.alignment = Alignment(wrap_text=True, vertical="center", horizontal="center")
        cell.border = THIN


def style_body(ws, start, end, ncols, highlight_rows=()):
    for r in range(start, end + 1):
        for c in range(1, ncols + 1):
            cell = ws.cell(r, c)
            cell.font = BODY_FONT
            cell.alignment = WRAP
            cell.border = THIN
            if r in highlight_rows:
                cell.fill = FILL_Y
            elif r % 2 == 0:
                cell.fill = FILL_A


def autosize(ws, widths):
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.row_dimensions[1].height = 22
    ws.row_dimensions[2].height = 28
    ws.freeze_panes = "A3"
    ws.auto_filter.ref = ws.dimensions


def add_sheet(wb, title, headers, rows, note, widths, highlight=()):
    ws = wb.create_sheet(title)
    ws["A1"] = title
    ws["A1"].font = TITLE_FONT
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=len(headers))
    for i, h in enumerate(headers, 1):
        ws.cell(2, i, h)
    for r, row in enumerate(rows, 3):
        for c, v in enumerate(row, 1):
            ws.cell(r, c, v)
    last = 2 + len(rows)
    style_header(ws, len(headers))
    style_body(ws, 3, last, len(headers), highlight_rows=tuple(i + 2 for i in highlight))
    note_row = last + 2
    ws.cell(note_row, 1, note).font = NOTE_FONT
    ws.merge_cells(start_row=note_row, start_column=1, end_row=note_row, end_column=len(headers))
    autosize(ws, widths)
    ws.page_setup.orientation = "landscape"
    ws.page_setup.fitToPage = True
    ws.page_setup.fitToWidth = 1
    ws.page_setup.fitToHeight = 0
    ws.print_title_rows = "1:2"
    return ws


