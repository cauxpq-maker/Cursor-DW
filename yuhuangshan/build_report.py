def set_font(run, name="宋体", size=12, bold=False, color=None):
    run.font.name = name
    run.font.size = Pt(size)
    run.font.bold = bold
    r = run._element.rPr
    rFonts = r.find(qn("w:rFonts"))
    rFonts.set(qn("w:eastAsia"), name)
    if color is not None:
        run.font.color.rgb = color


def para(text, size=12, bold=False, align=None, color=None, font="宋体",
         space_after=6, indent=True, line=1.4):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.line_spacing = line
    if indent and align is None:
        p.paragraph_format.first_line_indent = Pt(size * 2)
    if align:
        p.alignment = align
    run = p.add_run(text)
    set_font(run, font, size, bold, color)
    return p


