def add_table(header, rows, widths=None, header_bg="2E6E4E", size=10.5):
    t = doc.add_table(rows=1 + len(rows), cols=len(header))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for j, htext in enumerate(header):
        cell = t.rows[0].cells[j]
        cell._tc.get_or_add_tcPr().append(
            parse_xml(f'<w:shd {nsdecls("w")} w:val="clear" w:fill="{header_bg}"/>'))
        p = cell.paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = p.add_run(htext)
        set_font(run, "微软雅黑", size, True, RGBColor(0xFF, 0xFF, 0xFF))
    for i, row in enumerate(rows):
        if i % 2 == 1:
            for cell in t.rows[i + 1].cells:
                cell._tc.get_or_add_tcPr().append(
                    parse_xml(f'<w:shd {nsdecls("w")} w:val="clear" w:fill="F2F6F3"/>'))
        for j, val in enumerate(row):
            cell = t.rows[i + 1].cells[j]
            p = cell.paragraphs[0]
            p.paragraph_format.space_after = Pt(2)
            run = p.add_run(str(val))
            set_font(run, "宋体", size, bold=(j == 0))
    if widths:
        for j, w in enumerate(widths):
            for row in t.rows:
                row.cells[j].width = Cm(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t


